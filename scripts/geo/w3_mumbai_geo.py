"""W3-09 Mumbai: park outline from the 12 gazette boundary points A-L (S.O. 229(E) draft, Annexure; same points as
docs/geo/research/W3-09-mumbai-np/method/sgnp_boundary_area.py), joined in order = a SCHEMATIC, not the true boundary.
Also an enlarged copy (x8, true shape, moved into the sea west of Mumbai) and lake/Kanheri points from the gazette ESZ table.
Writes src/geo/week3/mumbai_geo.ts."""
def dms(d, m, s): return d + m/60 + s/3600
P = {'A': (dms(19,20,26.91), dms(72,54,27.07)), 'B': (dms(19,19,49.81), dms(72,55,44.18)),
 'C': (dms(19,17,6.50), dms(72,55,53.31)), 'D': (dms(19,15,32.08), dms(72,58,11.00)),
 'E': (dms(19,12,20.36), dms(72,56,59.00)), 'F': (dms(19,10,1.07), dms(72,55,49.04)),
 'G': (dms(19,8,34.24), dms(72,53,37.85)), 'H': (dms(19,10,53.22), dms(72,52,24.63)),
 'I': (dms(19,14,17.20), dms(72,52,27.43)), 'J': (dms(19,15,56.40), dms(72,52,52.39)),
 'K': (dms(19,17,11.84), dms(72,53,25.24)), 'L': (dms(19,17,27.11), dms(72,54,40.80))}
ring = [(lon, lat) for lat, lon in (P[k] for k in 'ABCDEFGHIJKL')]
cx = sum(p[0] for p in ring)/len(ring); cy = sum(p[1] for p in ring)/len(ring)
K, IX, IY = 8, 71.7, 19.2
big = lambda p: (round(IX + K*(p[0]-cx), 4), round(IY + K*(p[1]-cy), 4))
pts = {'TULSI': (dms(72,55,0.72), dms(19,11,25.99)), 'VIHAR': (dms(72,55,22.43), dms(19,8,45.58))}
f = lambda ps: "[" + ", ".join(f"[{p[0]:.4f}, {p[1]:.4f}]" for p in ps) + "]"
out = ["// GENERATED by scripts/geo/w3_mumbai_geo.py. Gazette S.O. 229(E) draft boundary points A-L (schematic ring).",
 'type P = [number, number];',
 f"export const PARK: P[] = {f(ring)};",
 f"export const PARK_C: P = [{cx:.4f}, {cy:.4f}];",
 f"export const PARK_X8: P[] = {f([big(p) for p in ring])};",
 f"export const INSET_C: P = [{IX}, {IY}];"]
for k, p in pts.items(): out.append(f"export const {k}_X8: P = {f([big(p)])[1:-1]};")
open('src/geo/week3/mumbai_geo.ts', 'w').write("\n".join(out) + "\n")
print("\n".join(out))
