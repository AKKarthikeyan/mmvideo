# W3-12 Thar: APPROXIMATE Jaisalmer district shape (no admin-2 geodata in the repo). East/north/south edges hand-placed inside
# 69.5-72.7°E, 26.0-28.0°N; the west edge follows India's outline (Natural Earth India view) moved 0.15° INSIDE, so the fill
# never crosses or traces the international boundary. Writes src/geo/week3/thar_geo.ts. Labelled "approx." on screen.
import json, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[2]
NE = json.load(open(ROOT / "sources/geo/ne_10m_admin_0_countries_ind.geojson"))
ind = next(f for f in NE["features"] if f["properties"].get("ADM0_A3") == "IND" or f["properties"].get("ISO_A3") == "IND")
g = ind["geometry"]; polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
edges = [(r[i], r[i + 1]) for p in polys for r in p for i in range(len(r) - 1)]
def west_lon(lat):   # India's westernmost boundary crossing at this latitude, between 68.5 and 71.5°E
    xs = [a[0] + (lat - a[1]) * (b[0] - a[0]) / (b[1] - a[1]) for a, b in edges if (a[1] - lat) * (b[1] - lat) < 0]
    xs = [x for x in xs if 68.5 < x < 71.5]
    return min(xs)
INSET = 0.15
west = [(round(max(69.5, west_lon(la / 100)) + INSET, 3), la / 100) for la in range(2620, 2786, 15)]   # 26.20 -> 27.85 N
east = [(72.4, 27.95), (72.65, 27.3), (72.35, 26.6), (71.5, 26.1), (70.6, 26.15)]
ring = [list(p) for p in west] + [[71.4, 28.0]] + [list(p) for p in east]
out = ROOT / "src/geo/week3/thar_geo.ts"
out.write_text("// GENERATED by scripts/geo/w3_thar_geo.py. Jaisalmer district, APPROXIMATE (west edge = India outline moved 0.15° inside).\n"
               f"export const JSM_APPROX: [number, number][] = {json.dumps(ring)};\n")
print(len(ring), west[0], west[-1])
