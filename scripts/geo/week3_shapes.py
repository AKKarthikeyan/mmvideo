# Week 3 "same scale" overlays (8 Nov 2026): a country's outline moved onto an Indian state at TRUE size.
# Each vertex keeps its east-west and north-south distance in km from the shape's centroid (local equidistant), so the moved
# outline has the right size and shape where it is drawn (the flat map uses cos(lat) at the camera centre).
# Source: Natural Earth 10m admin-0, India point of view (house file). Writes src/geo/week3/shapes.ts.
#   python3 -I scripts/geo/week3_shapes.py
import json, math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NE = json.load(open(ROOT / "sources/geo/ne_10m_admin_0_countries_ind.geojson"))
ST = json.load(open(ROOT / "sources/geo/ne_10m_admin_1_states_provinces.geojson"))
K = 111.32

def rings_of(geom):
    polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
    return [p[0] for p in polys]

def area(r):   # km², local equal-area
    lat0 = sum(y for _, y in r) / len(r); c = math.cos(math.radians(lat0))
    return abs(sum((r[i][0] * r[i - 1][1] - r[i - 1][0] * r[i][1]) for i in range(len(r)))) / 2 * K * K * c

def centroid(rings):   # polygon (shoelace) centroid over the outer rings, in lon/lat
    sx = sy = sa = 0
    for r in rings:
        for i in range(len(r)):
            (x0, y0), (x1, y1) = r[i - 1], r[i]; cr = x0 * y1 - x1 * y0
            sa += cr; sx += (x0 + x1) * cr; sy += (y0 + y1) * cr
    return sx / (3 * sa), sy / (3 * sa)

def dpring(r, tol):   # closed ring: split at the vertex farthest from the first, simplify both halves
    j = max(range(len(r)), key=lambda i: (r[i][0] - r[0][0]) ** 2 + (r[i][1] - r[0][1]) ** 2)
    return dp(r[:j + 1], tol)[:-1] + dp(r[j:], tol)

def dp(pts, tol):   # Douglas-Peucker in degrees
    if len(pts) < 3: return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]; L = math.hypot(x2 - x1, y2 - y1) or 1e-12
    d = [abs((y2 - y1) * x - (x2 - x1) * y + x2 * y1 - y2 * x1) / L for x, y in pts[1:-1]]
    i = max(range(len(d)), key=d.__getitem__)
    if d[i] <= tol: return [pts[0], pts[-1]]
    return dp(pts[:i + 2], tol)[:-1] + dp(pts[i + 1:], tol)

def country(iso): return next(f for f in NE["features"] if f["properties"].get("ADM0_A3") == iso)
def state(name): return next(f for f in ST["features"] if f["properties"].get("name") == name and f["properties"].get("adm0_a3") == "IND")

def moved(iso, onto, keep=3, min_km2=2500, tol=0.03):
    rings = sorted(rings_of(country(iso)["geometry"]), key=area, reverse=True)
    rings = [r for r in rings[:keep] if area(r) >= min_km2]
    lon0, lat0 = centroid(rings); lon1, lat1 = centroid(rings_of(state(onto)["geometry"]))
    out = []
    for r in rings:
        rr = []
        for x, y in dpring(r, tol):
            dy = (y - lat0) * K; dx = (x - lon0) * K * math.cos(math.radians(y))
            ny = lat1 + dy / K; nx = lon1 + dx / (K * math.cos(math.radians(ny)))
            rr.append([round(nx, 3), round(ny, 3)])
        out.append(rr)
    return out, (round(lon1, 3), round(lat1, 3)), round(sum(area(r) for r in rings))

OVER = {"UK_ON_UP": ("GBR", "Uttar Pradesh"), "DEU_ON_RJ": ("DEU", "Rajasthan"), "FIN_ON_RJ": ("FIN", "Rajasthan")}
lines = ["// GENERATED by scripts/geo/week3_shapes.py (Natural Earth 10m, India POV). Outlines moved at TRUE size onto a state.", "type P = [number, number];"]
for name, (iso, onto) in OVER.items():
    rings, c, a = moved(iso, onto)
    print(name, len(rings), "rings", [len(r) for r in rings], "centre", c, "outline area ~", a, "km²")
    lines.append(f"export const {name}: P[][] = {json.dumps(rings, separators=(',', ':'))};   // {iso} onto {onto}, ~{a:,} km² of outline")
    lines.append(f"export const {name}_C: P = [{c[0]}, {c[1]}];")
up = rings_of(state("Uttar Pradesh")["geometry"]); print("UP state area ~", round(sum(area(r) for r in up)), "km²")
(ROOT / "src/geo/week3").mkdir(exist_ok=True)
(ROOT / "src/geo/week3/shapes.ts").write_text("\n".join(lines) + "\n")
