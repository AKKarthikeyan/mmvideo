"""Build src/looks/cartoon/long/scenes/globe_land.ts: simplified land rings for the cartoon globe.
Source: Natural Earth 10 m countries, India's point of view (public domain). Output: [lon,lat,...] rings, 1 decimal."""
import json, math
SRC = "/Volumes/DarwinSSD/MMVideo/sources/geo/ne_10m_admin_0_countries_ind.geojson"
OUT = "src/looks/cartoon/long/scenes/globe_land.ts"
def dp(pts, tol):
    if len(pts) < 3: return pts
    a, b = pts[0], pts[-1]; dx, dy = b[0]-a[0], b[1]-a[1]; n = math.hypot(dx, dy)
    best, bi = -1, 0
    for i in range(1, len(pts)-1):
        p = pts[i]
        d = math.hypot(p[0]-a[0], p[1]-a[1]) if n == 0 else abs(dy*(p[0]-a[0]) - dx*(p[1]-a[1])) / n
        if d > best: best, bi = d, i
    if best <= tol: return [a, b]
    return dp(pts[:bi+1], tol)[:-1] + dp(pts[bi:], tol)
d = json.load(open(SRC)); land, india = [], []
for f in d["features"]:
    a3 = f["properties"].get("ADM0_A3"); g = f["geometry"]
    if a3 == "ATA": continue
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    for poly in polys:
        ring = poly[0]; xs = [p[0] for p in ring]; ys = [p[1] for p in ring]
        isI = a3 == "IND"
        w = max(max(xs)-min(xs), max(ys)-min(ys)); near = 79 < xs[0] < 82.5 and 5 < ys[0] < 10.5
        if not isI and w < (0.8 if near else 3): continue
        # India keeps every island (Andaman and Nicobar, Lakshadweep): an official-view map of India must show them.
        r = dp([(p[0], p[1]) for p in ring], (0.12 if w >= 1.2 else 0.02) if isI else 0.45)
        if len(r) < 4 and not isI: continue
        if len(r) < 4: r = [(p[0], p[1]) for p in ring]
        flat = [round(v, 1) for p in r for v in p]
        (india if isI else land).append(flat)
js = lambda L: "[" + ",".join("[" + ",".join(str(v) for v in r) + "]" for r in L) + "]"
open(OUT, "w").write("// GENERATED by scripts/upsc/globe_land.py from Natural Earth 10 m (India's view, public domain). Rings are [lon,lat,lon,lat,...].\n"
  f"export const LAND: number[][] = {js(land)};\nexport const INDIA: number[][] = {js(india)};\n")
print(len(land), len(india), sum(len(r) for r in land)//2, sum(len(r) for r in india)//2)
