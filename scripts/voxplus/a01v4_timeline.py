#!/usr/bin/env python3
"""A01 v4 film timeline: beat start times from the voiced files (public/voxplus/a01v4/vo/timing.json).
Cold open c01-c05 keeps the approved stage-1 starts; title card 63.3-65.8 s; then each beat follows the last with a
0.35 s gap, 1.3 s before a chapter question (the chapter card shows first), the script's holds after m03 (+0.5),
n04 (+0.6), w06 (+0.3); e01 is followed by a 1.0 s hold and a 5.0 s end card.
Writes src/voxplus/a01v4Timing.ts (BEAT starts, DUR, TOTAL) and vo/timeline.json (also used for the SRT and hook check)."""
import json, pathlib
MM = pathlib.Path("/Volumes/DarwinSSD/MMVideo")
T = json.loads((MM / "public/voxplus/a01v4/vo/timing.json").read_text())
ORDER = "c01 c02 c03 c04 c05 m01 m02 m03 m04 m05 m06 n01 n02 n03 n04 n05 w01 w02 w03 w04 w05 w06 w07 w08 w09 w10 f01 f02 f03 f04 s01 s02 l01 l02 l03 l04 l05 l06 l07 x01 x02 x03 e01".split()
COLD = {"c01": 0.0, "c02": 14.1, "c03": 25.2, "c04": 38.65, "c05": 49.4}
CHAP = {"n01", "w01", "f01", "s01", "l01", "x01"}
HOLD = {"m03": 0.5, "n04": 0.6, "w06": 0.3}
start, t = {}, 0.0
for k in ORDER:
    if k in COLD: start[k] = COLD[k]; continue
    if k == "m01": t = 66.6
    start[k] = round(t, 2)
    nxt = ORDER[ORDER.index(k) + 1] if k != "e01" else None
    t = start[k] + T[k]["dur"] + HOLD.get(k, 0) + (1.3 if nxt in CHAP else 0.35)
total = round(start["e01"] + T["e01"]["dur"] + 1.0 + 5.0, 2)
dur = {k: T[k]["dur"] for k in ORDER}
ts = ("// generated by scripts/voxplus/a01v4_timeline.py from the voiced files: do not edit by hand\n"
      f"export const BEAT: Record<string, number> = {json.dumps(start)};\n"
      f"export const BEAT_DUR: Record<string, number> = {json.dumps(dur)};\n"
      f"export const BEAT_ORDER = {json.dumps(ORDER)};\n"
      f"export const FILM_TOTAL_S = {total};\n")
(MM / "src/voxplus/a01v4Timing.ts").write_text(ts)
(MM / "public/voxplus/a01v4/vo/timeline.json").write_text(json.dumps({"start": start, "total": total, "order": ORDER}, indent=1))
for k in ORDER: print(k, start[k], dur[k])
print("TOTAL", total, "= %d:%04.1f" % (total // 60, total % 60))
