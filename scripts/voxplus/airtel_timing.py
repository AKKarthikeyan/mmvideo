# Film timing for "Airtel's Moat: Price, Mix or Convergence?" -> src/voxplus/airtel/airtelTiming.ts (same shape as scaleTiming.ts).
#   python3 scripts/voxplus/airtel_timing.py             real: needs public/voxplus/airtel/vo/beats.json + words.json (after airtel_voice.py and airtel_words.py)
#   python3 scripts/voxplus/airtel_timing.py --estimate  PROVISIONAL: no audio; length from word count (125 wpm), word times spread by letters.
# Gaps are the scale film's: PARA_GAP 0.4, SCENE_GAP 0.8, START 0.35, TAIL 4.0. Re-run after any re-voice.
import json, pathlib, re, sys
R = pathlib.Path("/Volumes/DarwinSSD/MMVideo")
PARA_GAP, SCENE_GAP, START, TAIL, WPM = 0.4, 0.8, 0.35, 4.0, 125.0
HOLD = {"s07p4": 5.0}   # beat -> extra reading hold in seconds (add after the voice, e.g. to let a chart finish)
EST = "--estimate" in sys.argv
if EST:
    s = (R / "scripts/voxplus/SCRIPT_airtel_convergence_moat_6nov.md").read_text(); B = []; WD = {}
    for n, title, body in re.findall(r"## (\d\d) \| [^|]+\| ([^\n]+)\n(.*?)(?=\n## |\Z)", s, re.S):
        say = re.search(r"\*\*SAY:\*\*\n(.*?)\n\*\*PICTURE", body, re.S).group(1)
        for i, p in enumerate([" ".join(p.split()) for p in say.strip().split("\n\n") if p.strip()], 1):
            k = f"s{n}p{i}"; toks = p.split(); sec = round(len(toks) / WPM * 60, 2)
            tot = sum(len(t) + 1 for t in toks); acc = 0; ws = []
            for t in toks:
                a = acc / tot * sec; acc += len(t) + 1; ws.append([t, round(a, 3), round(min(sec, acc / tot * sec - 0.04), 3)])
            B.append({"key": k, "scene": int(n), "say": p, "sec": sec}); WD[k] = ws
else:
    B = json.load(open(R / "public/voxplus/airtel/vo/beats.json")); WD = json.load(open(R / "public/voxplus/airtel/vo/words.json"))
t, beat, dur, say, scene, order = START, {}, {}, {}, {}, []
for i, b in enumerate(B):
    k = b["key"]
    if i and b["scene"] != B[i - 1]["scene"]: t += SCENE_GAP - PARA_GAP
    beat[k], dur[k], say[k], scene[k] = round(t, 3), b["sec"], b["say"], b["scene"]; order.append(k)
    t += b["sec"] + PARA_GAP + HOLD.get(k, 0)
total = round(t - PARA_GAP + TAIL, 3)
miss = [k for k in order if not WD.get(k)]
if miss: raise SystemExit(f"no word timings for {miss}")
sstart = {}
for k in order: sstart.setdefault(scene[k], beat[k])
js = lambda o: json.dumps(o, ensure_ascii=False, separators=(",", ":"))
head = ("// PROVISIONAL (no voice yet): estimated from word counts at 125 wpm by scripts/voxplus/airtel_timing.py --estimate. Do not final-render from this file.\n"
        if EST else "// generated by scripts/voxplus/airtel_timing.py from the voiced beats and whisper word times: do not edit by hand.\n")
(R / "src/voxplus/airtel/airtelTiming.ts").write_text(
    head + "// Beat starts (film seconds), voiced lengths, narration, scene of each beat, scene starts and word times (seconds into the beat).\n"
    f"export const PROVISIONAL = {'true' if EST else 'false'};\n"
    f"export const FILM_TOTAL_S = {total};\nexport const ORDER: string[] = {js(order)};\n"
    f"export const BEAT: Record<string, number> = {js(beat)};\nexport const DUR: Record<string, number> = {js(dur)};\n"
    f"export const SCENE: Record<string, number> = {js(scene)};\nexport const SCENE_START: Record<number, number> = {js(sstart)};\n"
    f"export const SAY: Record<string, string> = {js(say)};\n"
    f"export const WORDS: Record<string, [string, number, number][]> = {js({k: WD[k] for k in order})};\n")
ends = sorted(sstart.items())
print(("PROVISIONAL " if EST else "") + f"{len(order)} beats, film {total/60:.2f} min ({total:.1f} s)")
for i, (sc, st) in enumerate(ends):
    en = ends[i + 1][1] if i + 1 < len(ends) else total
    print(f"  scene {sc:02d}: starts {st:7.2f}s, {en - st:6.1f}s, {sum(len(say[k].split()) for k in order if scene[k] == sc)} words")
