# Jio VoxPlus film timing (20 Oct 2026): beat starts from the voiced files (public/vx/jioipo/data.json) and word times
# (public/voxplus/jio/vo/words.json, mlx-whisper) -> src/voxplus/jio/jioTiming.ts. Re-run after any re-voice.
import json, pathlib
R = pathlib.Path("/Volumes/DarwinSSD/MMVideo")
D = json.load(open(R / "public/vx/jioipo/data.json"))
WD = json.load(open(R / "public/voxplus/jio/vo/words.json"))
GAP, TITLE_GAP, PRE_TITLE, TAIL = 0.45, 0.7, 0.6, 3.5
t, beat, dur, order, say = 0.6, {}, {}, [], {}
bs = D["beats"]
for i, b in enumerate(bs):
    k = b["key"]
    if b["scene"]["type"] == "title" and i: t += PRE_TITLE
    beat[k], dur[k] = round(t, 3), b["sec"]; order.append(k); say[k] = b["say"]
    t += b["sec"] + (TITLE_GAP if b["scene"]["type"] == "title" else GAP)
total = round(t - GAP + TAIL, 3)
words = {k: WD.get(k, []) for k in order}
missing = [k for k in order if not words[k]]
if missing: raise SystemExit(f"no word timings for {missing}")
js = lambda o: json.dumps(o, ensure_ascii=False, separators=(",", ":"))
out = R / "src/voxplus/jio/jioTiming.ts"
out.write_text(
    "// generated by scripts/voxplus/jio_timing.py: do not edit by hand. Beat starts (film seconds), voiced lengths,\n"
    "// narration and word times (seconds into the beat) for the Jio IPO review film.\n"
    f"export const FILM_TOTAL_S = {total};\n"
    f"export const ORDER: string[] = {js(order)};\n"
    f"export const BEAT: Record<string, number> = {js(beat)};\n"
    f"export const DUR: Record<string, number> = {js(dur)};\n"
    f"export const SAY: Record<string, string> = {js(say)};\n"
    f"export const WORDS: Record<string, [string, number, number][]> = {js(words)};\n")
print(f"{len(order)} beats, film {total/60:.2f} min -> {out}")
