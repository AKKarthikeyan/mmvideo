# Timing for the five Jio moat Shorts: start offset, voiced length, words -> src/voxplus/scale/shorts/shortsTiming.ts
import json, pathlib
R = pathlib.Path("/Volumes/DarwinSSD/MMVideo")
B = json.load(open(R / "public/voxplus/scale/shorts/vo/beats.json")); W = json.load(open(R / "public/voxplus/scale/shorts/vo/words.json"))
START, TAIL = 0.3, 2.8
js = lambda o: json.dumps(o, ensure_ascii=False, separators=(",", ":"))
miss = [b["key"] for b in B if not W.get(b["key"])]
if miss: raise SystemExit(f"no words for {miss}")
info = {b["key"]: {"title": b["title"], "say": b["say"], "dur": b["sec"], "total": round(START + b["sec"] + TAIL, 3)} for b in B}
(R / "src/voxplus/scale/shorts/shortsTiming.ts").write_text(
    "// generated by scripts/voxplus/scale_shorts_timing.py: do not edit by hand.\n"
    f"export const START = {START};\nexport const TAIL = {TAIL};\n"
    f"export const SHORTS: Record<string, {{title: string; say: string; dur: number; total: number}}> = {js(info)};\n"
    f"export const WORDS: Record<string, [string, number, number][]> = {js({k: W[k] for k in info})};\n")
print({k: v["total"] for k, v in info.items()})
