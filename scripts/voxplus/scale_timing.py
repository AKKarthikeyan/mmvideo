# Film timing for "Jio's Size Advantage Has a Catch" (20 Oct 2026): beat starts from voiced lengths + gaps + reading holds
# (AK brief: let charts finish; hold the debt reconciliation ~4 s) -> src/voxplus/scale/scaleTiming.ts. Re-run after any re-voice.
import json, pathlib
R = pathlib.Path("/Volumes/DarwinSSD/MMVideo")
B = json.load(open(R / "public/voxplus/scale/vo/beats.json")); WD = json.load(open(R / "public/voxplus/scale/vo/words.json"))
PARA_GAP, SCENE_GAP, START, TAIL = 0.4, 0.8, 0.35, 4.0
HOLD = {"s11p3": 0.5}   # AK 20 Oct 2026: no long pauses (was 1.0-3.0 s holds after 9 beats); keep a short beat after the reconciliation
t, beat, dur, say, scene, order = START, {}, {}, {}, {}, []
for i, b in enumerate(B):
    k = b["key"]
    if i and b["scene"] != B[i - 1]["scene"]: t += SCENE_GAP - PARA_GAP
    beat[k], dur[k], say[k], scene[k] = round(t, 3), b["sec"], b["say"], b["scene"]; order.append(k)
    t += b["sec"] + PARA_GAP + HOLD.get(k, 0)
total = round(t - PARA_GAP + TAIL, 3)
miss = [k for k in order if not WD.get(k)]
if miss: raise SystemExit(f"no word timings for {miss}")
sstart = {}
for k in order: sstart.setdefault(scene[k], beat[k])
js = lambda o: json.dumps(o, ensure_ascii=False, separators=(",", ":"))
(R / "src/voxplus/scale/scaleTiming.ts").write_text(
    "// generated by scripts/voxplus/scale_timing.py: do not edit by hand. Beat starts (film seconds), voiced lengths,\n"
    "// narration, scene of each beat, scene starts and word times (seconds into the beat).\n"
    f"export const FILM_TOTAL_S = {total};\nexport const ORDER: string[] = {js(order)};\n"
    f"export const BEAT: Record<string, number> = {js(beat)};\nexport const DUR: Record<string, number> = {js(dur)};\n"
    f"export const SCENE: Record<string, number> = {js(scene)};\nexport const SCENE_START: Record<number, number> = {js(sstart)};\n"
    f"export const SAY: Record<string, string> = {js(say)};\n"
    f"export const WORDS: Record<string, [string, number, number][]> = {js({k: WD[k] for k in order})};\n")
print(f"{len(order)} beats, film {total/60:.2f} min")
